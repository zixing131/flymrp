import { getStore } from '@edgeone/pages-blob';
import { readFile, writeFile, appendFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const token=process.env.EDGEONE_PAGES_API_TOKEN || (await readFile(process.env.EDGEONE_TOKEN_FILE,'utf8')).trim();
const projectId='makers-gciglthrse9a';
const store=getStore({name:'my-store',projectId,token,consistency:'strong'});
const hash=(b,a='sha256')=>createHash(a).update(b).digest('hex');
const games=JSON.parse(await readFile('artifacts/compat-20260914/store-manifest.json','utf8')).games;
const rows=(await readFile('artifacts/edgeone/uploaded.jsonl','utf8')).trim().split('\n').map(JSON.parse);
const large=[...new Map(rows.filter(r=>r.projectId===projectId).map(r=>[r.key,r])).values()].filter(r=>r.bytes>2000000);
const map={}, verified=new Set();
for(const r of large){
 const game=games.find(g=>g.down.replace(/^\//,'')===r.key);
 const path=r.kind==='mrp' ? game.localPath || `artifacts/compat-20260914/packages/${game.md5}.mrp` : r.key.startsWith('runtime/') ? `dist/${r.key.slice('runtime/'.length)}` : `artifacts/edgeone/downloads/${r.key}`;
 const bytes=await readFile(path);if(hash(bytes)!==r.sha256) throw new Error(`Source changed: ${r.key}`);
 const parts=[];
 for(let offset=0,index=0;offset<bytes.length;offset+=1900000,index++){
  const b=bytes.subarray(offset,offset+1900000),key=`chunks/${r.sha256}/${index}`,sha256=hash(b);
  if(!verified.has(key)){
   try{await store.set(key,new Blob([b]),{onlyIfNew:true,cacheControl:'public, max-age=31536000, immutable'});}catch(e){if(e.code!=='PRECONDITION_FAILED')throw e;}
   const remote=await store.get(key,{type:'arrayBuffer',consistency:'strong'});
   if(!remote||hash(Buffer.from(remote))!==sha256)throw new Error(`Chunk verification failed: ${key}`);
   verified.add(key);await appendFile('artifacts/edgeone/chunks-verified.jsonl',JSON.stringify({key,bytes:b.length,sha256,verifiedAt:new Date().toISOString()})+'\n');
  }
  parts.push({key,size:b.length,md5:hash(b,'md5'),sha256});
 }
 map[r.key]={version:1,size:bytes.length,md5:hash(bytes,'md5'),sha256:r.sha256,parts};
 console.log('Chunked',r.key,bytes.length,parts.length);
}
await store.setJSON('api/chunks.json',map,{cacheControl:'no-cache'});
await writeFile('blob-config/chunks.js','// Generated by tools/edgeone/chunk-large.mjs. No credentials.\nexport default '+JSON.stringify(map,null,2)+';\n');
await writeFile('artifacts/edgeone/chunks-summary.json',JSON.stringify({files:Object.keys(map).length,uniqueChunks:verified.size,maxChunkBytes:1900000,filesByKey:map},null,2)+'\n');
console.log('Verified',Object.keys(map).length,'files;',verified.size,'unique chunks');
